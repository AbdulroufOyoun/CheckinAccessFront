#!/usr/bin/env node
/**
 * Validates tenant-label-catalog.json against en.json/ar.json and regenerates:
 * - src/app/settings/tenant-label-catalog.generated.ts
 * - ../CheckinAccess/app/Support/generated/TenantLabelOverrideKeys.php
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontRoot = path.resolve(__dirname, '..');
const backRoot = path.resolve(frontRoot, '..', 'CheckinAccess');

const catalogPath = path.join(__dirname, 'tenant-label-catalog.json');
const enPath = path.join(frontRoot, 'src/assets/i18n/en.json');
const arPath = path.join(frontRoot, 'src/assets/i18n/ar.json');
const tsOut = path.join(frontRoot, 'src/app/settings/tenant-label-catalog.generated.ts');
const phpOut = path.join(backRoot, 'app/Support/generated/TenantLabelOverrideKeys.php');

const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
const en = JSON.parse(fs.readFileSync(enPath, 'utf8'));
const ar = JSON.parse(fs.readFileSync(arPath, 'utf8'));

const maxPhase = catalog.activePhase ?? 1;
const entries = catalog.entries.filter((e) => e.phase <= maxPhase);
const keySet = new Set(entries.map((e) => e.key));

const errors = [];
for (const e of entries) {
  if (!(e.key in en)) {
    errors.push(`Missing in en.json: ${e.key}`);
  }
  if (!(e.key in ar)) {
    errors.push(`Missing in ar.json: ${e.key}`);
  }
}

for (const group of catalog.groups) {
  for (const key of group.keys) {
    if (!keySet.has(key)) {
      errors.push(`Group ${group.id} references key not in entries (phase<=${maxPhase}): ${key}`);
    }
  }
}

for (const e of entries) {
  const inGroup = catalog.groups.some((g) => g.keys.includes(e.key));
  if (!inGroup) {
    errors.push(`Entry not assigned to any group: ${e.key}`);
  }
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const allKeys = [...keySet].sort();
const modules = [...new Set(entries.map((e) => e.module))].sort();

const metaLines = entries
  .sort((a, b) => a.key.localeCompare(b.key))
  .map(
    (e) =>
      `  '${e.key}': { module: '${e.module}', page: '${e.page ?? ''}', kind: '${e.kind}', phase: ${e.phase} },`,
  )
  .join('\n');

const groupBlocks = catalog.groups
  .map((g) => {
    const keys = g.keys.filter((k) => keySet.has(k));
    const keysLiteral = keys.map((k) => `'${k}'`).join(', ');
    return `  {
    id: '${g.id}',
    titleKey: '${g.titleKey}',
    hintKey: '${g.hintKey}',
    module: '${g.module}',
    keys: [${keysLiteral}],
  }`;
  })
  .join(',\n');

const ts = `/* eslint-disable */
/** Generated by scripts/sync-tenant-label-catalog.mjs — do not edit. */
export type TenantLabelModule = ${modules.map((m) => `'${m}'`).join(' | ')};

export interface TenantLabelMeta {
  module: TenantLabelModule;
  page: string;
  kind: string;
  phase: number;
}

export const TENANT_LABEL_META: Record<string, TenantLabelMeta> = {
${metaLines}
};

export const TENANT_LABEL_MODULES: readonly TenantLabelModule[] = ${JSON.stringify(modules)} as const;

export const TENANT_LABEL_GROUPS_GENERATED = [
${groupBlocks},
] as const;

export const TENANT_LABEL_KEYS_GENERATED = [
${allKeys.map((k) => `  '${k}',`).join('\n')}
] as const;
`;

const phpKeys = allKeys.map((k) => `        '${k}',`).join('\n');
const php = `<?php

/** Generated by CheckinAccessFront/scripts/sync-tenant-label-catalog.mjs — do not edit. */

return [
${phpKeys}
];
`;

fs.mkdirSync(path.dirname(phpOut), { recursive: true });
fs.writeFileSync(tsOut, ts);
fs.writeFileSync(phpOut, php);
console.log(`Synced ${allKeys.length} label keys (phase<=${maxPhase}) →`);
console.log(`  ${path.relative(process.cwd(), tsOut)}`);
console.log(`  ${path.relative(process.cwd(), phpOut)}`);
